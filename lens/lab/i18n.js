export function translate(language, key, values={}) {
  const message=messages[language]?.[key] ?? messages.zh[key];
  if(message===undefined)throw new Error(`Missing translation: ${key}`);
  return message.replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??`{${name}}`));
}

export function createI18n() {
  let saved; try{saved=localStorage.getItem('glass-language');}catch{}
  const requested=new URLSearchParams(location.search).get('lang');
  let language=[requested,document.documentElement.dataset.defaultLanguage,saved,'zh'].find(value=>value==='zh'||value==='en');
  const api={
    get language(){return language;},
    t:(key,values)=>translate(language,key,values),
    set(value){
      language=value==='en'?'en':'zh';
      document.documentElement.lang=language==='zh'?'zh-CN':'en';
      for(const [attribute,target] of [['data-i18n',null],['data-i18n-aria','aria-label'],['data-i18n-placeholder','placeholder'],['data-i18n-title','title'],['data-i18n-content','content']]){
        document.querySelectorAll(`[${attribute}]`).forEach(element=>{
          const text=api.t(element.getAttribute(attribute));
          if(target)element.setAttribute(target,text);else element.textContent=text;
        });
      }
      document.querySelectorAll('[data-language]').forEach(button=>button.setAttribute('aria-pressed',String(button.dataset.language===language)));
      try{localStorage.setItem('glass-language',language);}catch{}
    }
  };
  api.set(language);return api;
}
